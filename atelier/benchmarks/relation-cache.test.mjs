import assert from "node:assert/strict";
import {createRelationCache} from "./relation-cache.mjs";
let calls=0;
const evaluate=(a,b)=>{calls++;return a.category===b.category?null:{ids:[a.id,b.id],colors:[a.color,b.color]}};
const a={id:"a",category:"Arriba",color:"Blanco"},b={id:"b",category:"Abajo",color:"Negro"},c={id:"c",category:"Zapatos",color:"Negro"};
const cache=createRelationCache({profileId:"noelia",engineVersion:"v1",pairEvidence:evaluate});
assert.deepEqual(cache.reconcile([a,b,c]),{dirty:3,garments:3,edges:0});
assert.deepEqual(cache.evidence("a","b")?.ids,["a","b"]);
assert.deepEqual(cache.evidence("b","a")?.ids,["a","b"]);
assert.equal(calls,1);
assert.equal(cache.neighbors("a").length,2);
assert.equal(calls,2);
assert.deepEqual(cache.reconcile([{...a},b,c]),{dirty:0,garments:3,edges:2});
assert.equal(cache.evidence("a","b").colors[0],"Blanco");
assert.equal(calls,2);
assert.equal(cache.reconcile([a,{...b,color:"Rojo"},c]).dirty,1);
assert.equal(cache.stats().edges,1,"Only the changed garment's edges must be removed");
assert.equal(cache.evidence("a","b").colors[1],"Rojo");
assert.equal(calls,3);
assert.equal(cache.evidence("a","c").colors[0],"Blanco");
assert.equal(calls,3,"Unchanged relationship should be preserved");
const beforeRename=cache.stats().calculated;
assert.equal(cache.reconcile([{...a,name:"Camisa sin mangas"}, {...b,color:"Rojo"}, c]).dirty,1);
cache.evidence("a","c");
assert.equal(cache.stats().calculated,beforeRename+1,"Name-only changes must invalidate related evidence");
assert.equal(cache.reconcile([a,c]).garments,2);
assert.equal(cache.evidence("a","b"),null,"Deleted or remote-removed pieces must disappear");
assert.equal(cache.neighbors("a").length,1);
const other=createRelationCache({profileId:"irene",engineVersion:"v1",pairEvidence:evaluate});
other.reconcile([a,b]);
assert.equal(other.stats().edges,0,"Profiles must not share derived relationships");
assert.throws(()=>cache.reconcile([a,a]),/Duplicate/);
const sameType={id:"x",category:"Arriba",color:"Gris"};
cache.reconcile([a,c,sameType]);
const beforeNull=cache.stats().calculated;
assert.equal(cache.evidence("a","x"),null);
assert.equal(cache.evidence("a","x"),null);
assert.equal(cache.stats().calculated,beforeNull+1,"Null evidence should also be cached once");
const v2=createRelationCache({profileId:"noelia",engineVersion:"v2",pairEvidence:evaluate});
v2.reconcile([a,b]);assert.equal(v2.stats().edges,0,"New engine versions do not reuse prior cache");
assert.throws(()=>createRelationCache({profileId:"",engineVersion:"v1",pairEvidence:evaluate}));
const ranked=createRelationCache({profileId:"noelia",engineVersion:"v1",pairEvidence:(left,right)=>({pair:[left.id,right.id]})});
ranked.reconcile([{id:"anchor",category:"Arriba"},{id:"ordinary",category:"Abajo"},{id:"favorite",category:"Abajo"}]);
assert.deepEqual(ranked.neighbors("anchor",{limit:1,rank:(_edge,g)=>g.id==="favorite"?100:1}).map(x=>x.garmentId),["favorite"],"A late-added garment must win on context, not wardrobe order");
assert.deepEqual(ranked.neighbors("anchor",{limit:1,rank:(_edge,g)=>g.id==="ordinary"?100:1}).map(x=>x.garmentId),["ordinary"],"A new context must rerank without stale cached preferences");
assert.throws(()=>ranked.neighbors("anchor",{rank:"invalid"}),/Invalid rank/);
console.log("Incremental relation cache tests: OK");
