import assert from "node:assert/strict";
import {scorePair,compatibleRoles,updateCompatibilityGraph,neighbors,minimalLooks} from "./compatibility-graph.mjs";
const top={id:"top",category:"Arriba",color:"Rojo",pattern:"floral",style:"casual"};
const trousers={id:"pants",category:"Abajo",color:"Negro",pattern:"plain",style:"casual"};
const shoes={id:"shoes",category:"Zapatos",color:"Blanco",pattern:"plain",style:"sport"};
const coat={id:"coat",category:"Capas",color:"Beige",style:"smart"};
const dress={id:"dress",category:"Vestidos",color:"Azul",style:"party"};
assert.equal(compatibleRoles(top,trousers),true);
assert.equal(compatibleRoles(dress,trousers),false,"Dress and bottoms should not normally stack");
assert.equal(scorePair(top,{...top,id:"top2"}),null);
assert.equal(scorePair(top,trousers)?.kind,"pair-estimate");
assert.equal(scorePair(top,{...trousers,pattern:"floral"}).score<scorePair(top,trousers).score,true);
const initial=updateCompatibilityGraph([top,trousers,shoes,coat,dress]);
assert.ok(initial.stats.relations>2);
assert.ok(neighbors(initial,"top").some(x=>x.garmentId==="pants"));
assert.ok(minimalLooks([top,trousers,shoes,coat,dress],initial).some(x=>x.garmentIds.length===2));
const same=updateCompatibilityGraph([top,trousers,shoes,coat,dress],initial);
assert.equal(same.stats.computed,0);
assert.equal(same.stats.reused,initial.stats.relations);
const changed=updateCompatibilityGraph([top,{...trousers,color:"Verde"},shoes,coat,dress],same);
assert.ok(changed.stats.computed>0);
assert.ok(changed.stats.reused>0);
const removed=updateCompatibilityGraph([top,trousers,shoes,{...coat,deleted:true},dress],initial);
assert.equal(removed.stats.garments,4);
assert.ok(Object.values(removed.edges).every(e=>e.a!=="coat"&&e.b!=="coat"));
assert.throws(()=>updateCompatibilityGraph([top,top]));
assert.deepEqual(minimalLooks([top,shoes],updateCompatibilityGraph([top,shoes])),[]);
console.log("incremental compatibility graph: OK");
