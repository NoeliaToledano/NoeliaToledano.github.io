import assert from "node:assert/strict";
import {evaluateCombination,expandCombination,buildCombinationGraph} from "./combination-hypergraph.mjs";
const top={id:"top",category:"Arriba",style:"casual",color:"Blanco",pattern:"plain"};
const bottom={id:"bottom",category:"Abajo",style:"casual",color:"Negro",pattern:"plain"};
const jacket={id:"jacket",category:"Capas",style:"smart",color:"Beige",pattern:"plain"};
const shoes={id:"shoes",category:"Zapatos",style:"sport",color:"Blanco",pattern:"plain"};
const pair=evaluateCombination([top,bottom]);
assert.equal(pair.valid,true);
assert.equal(pair.aesthetic,"casual");
assert.ok(pair.contexts.includes("daily"));
const triple=evaluateCombination([top,bottom,jacket]);
assert.equal(triple.valid,true);
assert.equal(triple.inspectedPairs,3);
assert.equal(expandCombination([top,bottom],jacket).expanded.garmentIds.length,3);
assert.equal(evaluateCombination([top,bottom,{id:"other",category:"Arriba"}]).valid,false);
const print=(id,category,color)=>({id,category,color,pattern:"floral",style:"casual"});
const many=evaluateCombination([print("a","Arriba","Rojo"),print("b","Abajo","Azul"),print("c","Zapatos","Verde")]);
assert.ok(many.problems.some(s=>s.includes("estampados")));
const four=evaluateCombination([top,{...bottom,color:"Azul"}, {...jacket,color:"Rojo"}, {...shoes,color:"Verde"}]);
assert.ok(four.problems.some(s=>s.includes("colores")));
const graph=buildCombinationGraph([top,bottom,jacket,shoes],{maxGroups:5});
assert.ok(graph.combinations.length>0&&graph.combinations.length<=5);
assert.ok(graph.combinations.every(x=>x.provisional));
assert.throws(()=>evaluateCombination([top,top]));
console.log("outfit hypergraph: OK");
